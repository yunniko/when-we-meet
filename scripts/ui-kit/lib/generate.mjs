// Turns resolved tokens into each platform's form (COMPANY/UI_STANDARDS.md §1). Each function returns file
// contents; writing and the freshness check are in ui-tokens.mjs. Output is deterministic, so "fresh" means
// "byte-identical to what the generator writes now".
import { coloursOf, toPx } from "./tokens.mjs";

const HEADER = "Generated by ui-kit from design/tokens.json. Do not edit: run `node scripts/ui-kit/ui-tokens.mjs`.";

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^[a-z]/, (c) => c.toUpperCase());
const snake = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/-/g, "_")
    .toLowerCase();
/** A member name that is valid in every target language: group prefix, then the token name. */
const member = (group, name) => camel(`${group}-${name}`);

/** Tailwind v4 theme namespaces (https://tailwindcss.com/docs/theme#theme-variable-namespaces). */
const TAILWIND = {
  color: "color",
  font: "font",
  fontSize: "text",
  fontWeight: "font-weight",
  space: "spacing",
  radius: "radius",
  shadow: "shadow",
  breakpoint: "breakpoint",
};

const cssValue = (group, v) =>
  group === "font" ? v.map((f) => (/[\s]/.test(f) && !f.startsWith("var(") ? `"${f}"` : f)).join(", ") : String(v);

/**
 * CSS custom properties plus a Tailwind v4 `@theme inline` block. The default Tailwind palette is removed
 * (`--color-*: initial`), so a class like `bg-red-500` does not compile at all.
 * @param {{modeSelectors?: Record<string, string>}} options a mode's CSS: a selector (`.dark`) or an at-rule
 *   (`@media (prefers-color-scheme: dark)`). Default: `dark` follows the system setting, others `[data-mode=…]`.
 */
export function toCss(resolved, options = {}) {
  const lines = [`/* ${HEADER} */`, "", ":root {"];
  for (const [group, tokens] of Object.entries(resolved.groups)) {
    for (const [name, t] of Object.entries(tokens)) lines.push(`  --ui-${snakeCss(group)}-${name}: ${cssValue(group, t.value)};`);
  }
  lines.push("}");
  for (const mode of Object.keys(resolved.modes)) {
    const sel = options.modeSelectors?.[mode] ?? (mode === "dark" ? "@media (prefers-color-scheme: dark)" : `[data-mode="${mode}"]`);
    const body = Object.entries(resolved.modes[mode].color).map(([name, t]) => `--ui-color-${name}: ${t.value};`);
    if (body.length === 0) continue;
    lines.push("");
    if (sel.startsWith("@")) lines.push(`${sel} {`, "  :root {", ...body.map((l) => `    ${l}`), "  }", "}");
    else lines.push(`${sel} {`, ...body.map((l) => `  ${l}`), "}");
  }
  lines.push("", "@theme inline {", "  --color-*: initial;");
  for (const [group, tokens] of Object.entries(resolved.groups)) {
    const ns = TAILWIND[group];
    if (!ns) continue;
    for (const [name, t] of Object.entries(tokens)) {
      // Breakpoints are read at build time inside media queries, where var() does not work.
      const value = group === "breakpoint" ? t.value : `var(--ui-${snakeCss(group)}-${name})`;
      lines.push(`  --${ns}-${name}: ${value};`);
    }
  }
  lines.push("}", "");
  return lines.join("\n");
}

function snakeCss(group) {
  return group.replace(/([A-Z])/g, (c) => `-${c.toLowerCase()}`);
}

const dartColor = (hex) => {
  const h = hex.slice(1);
  const argb = h.length === 8 ? h.slice(6) + h.slice(0, 6) : `ff${h}`;
  return `Color(0x${argb.toUpperCase()})`;
};
const dartNum = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

/** A Flutter file: one `UiTokens` class of constants, a `UiPalette` per mode, and a ColorScheme from a palette. */
export function toDart(resolved) {
  const roles = Object.keys(resolved.groups.color);
  const out = [`// ${HEADER}`, "// ignore_for_file: constant_identifier_names", "", "import 'package:flutter/material.dart';", ""];

  out.push("abstract final class UiTokens {");
  for (const [group, tokens] of Object.entries(resolved.groups)) {
    if (group === "color" || group === "breakpoint") continue;
    for (const [name, t] of Object.entries(tokens)) {
      const id = member(group, name);
      if (group === "font") out.push(`  static const String ${id} = '${t.value[0].replace(/'/g, "\\'")}';`);
      else if (group === "fontWeight") out.push(`  static const FontWeight ${id} = FontWeight.w${Math.round(t.value / 100) * 100};`);
      else if (group === "duration") out.push(`  static const Duration ${id} = Duration(milliseconds: ${parseInt(t.value, 10)});`);
      else if (group === "shadow") out.push(`  static const double ${id} = ${dartNum(t.dp)};`);
      else out.push(`  static const double ${id} = ${dartNum(toPx(t.value))};`);
    }
  }
  out.push("}", "");

  out.push("class UiPalette {", "  const UiPalette({");
  for (const r of roles) out.push(`    required this.${camel(r)},`);
  out.push("  });", "");
  for (const r of roles) out.push(`  final Color ${camel(r)};`);
  out.push("");
  const palette = (name, colours) => {
    out.push(`  static const UiPalette ${name} = UiPalette(`);
    for (const r of roles) out.push(`    ${camel(r)}: ${dartColor(colours[r])},`);
    out.push("  );");
  };
  palette("base", coloursOf(resolved));
  for (const mode of Object.keys(resolved.modes)) palette(camel(mode), coloursOf(resolved, mode));
  out.push(
    "",
    "  /// The Material colour scheme these roles map onto; one mapping for every Flutter project.",
    "  ColorScheme toColorScheme(Brightness brightness) => ColorScheme(",
    "        brightness: brightness,",
    "        primary: accent,",
    "        onPrimary: onAccent,",
    "        secondary: accent,",
    "        onSecondary: onAccent,",
    "        error: danger,",
    "        onError: surface,",
    "        surface: surface,",
    "        onSurface: text,",
    "        onSurfaceVariant: textMuted,",
    "        surfaceContainer: surfaceRaised,",
    "        outline: border,",
    "      );",
    "}",
    ""
  );
  return out.join("\n");
}

const xmlEscape = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const androidColor = (hex) => {
  const h = hex.slice(1).toUpperCase();
  return h.length === 8 ? `#${h.slice(6)}${h.slice(0, 6)}` : `#${h}`;
};

/**
 * Android resources: `values/ui_tokens.xml` and, when a `dark` mode exists, `values-night/ui_tokens.xml`.
 * Android has no other theme qualifier, so other modes are left out (and the caller is told).
 * @returns {{files: Record<string, string>, skippedModes: string[]}} paths relative to the res directory.
 */
export function toAndroid(resolved) {
  const doc = (body) =>
    ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${xmlEscape(HEADER)} -->`, "<resources>", ...body, "</resources>", ""].join("\n");
  const colours = (c) => Object.entries(c).map(([name, hex]) => `    <color name="ui_color_${snake(name)}">${androidColor(hex)}</color>`);
  const body = [...colours(coloursOf(resolved))];
  for (const [group, tokens] of Object.entries(resolved.groups)) {
    for (const [name, t] of Object.entries(tokens)) {
      const id = `ui_${snake(group)}_${snake(name)}`;
      if (group === "fontSize") body.push(`    <dimen name="${id}">${toPx(t.value)}sp</dimen>`);
      else if (group === "space" || group === "radius" || group === "breakpoint")
        body.push(`    <dimen name="${id}">${toPx(t.value)}dp</dimen>`);
      else if (group === "shadow") body.push(`    <dimen name="${id}">${t.dp}dp</dimen>`);
      else if (group === "duration") body.push(`    <integer name="${id}">${parseInt(t.value, 10)}</integer>`);
      else if (group === "fontWeight") body.push(`    <integer name="${id}">${t.value}</integer>`);
      else if (group === "font") body.push(`    <string name="${id}" translatable="false">${xmlEscape(t.value[0])}</string>`);
    }
  }
  const files = { "values/ui_tokens.xml": doc(body) };
  const skippedModes = [];
  for (const mode of Object.keys(resolved.modes)) {
    if (mode === "dark")
      files["values-night/ui_tokens.xml"] = doc(
        colours(Object.fromEntries(Object.entries(resolved.modes.dark.color).map(([k, v]) => [k, v.value])))
      );
    else skippedModes.push(mode);
  }
  return { files, skippedModes };
}

const avaloniaColor = (hex) => {
  const h = hex.slice(1).toUpperCase();
  return h.length === 8 ? `#${h.slice(6)}${h.slice(0, 6)}` : `#${h}`;
};

/** An Avalonia ResourceDictionary: colours and brushes per theme variant (Default, and Dark when defined). */
export function toAvalonia(resolved) {
  const out = [
    '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
    `  <!-- ${xmlEscape(HEADER)} -->`,
  ];
  const themed = (key, colours) => {
    out.push(`    <ResourceDictionary x:Key="${key}">`);
    for (const [name, hex] of Object.entries(colours)) {
      const id = pascal(member("color", name));
      out.push(`      <Color x:Key="Ui${id}">${avaloniaColor(hex)}</Color>`);
      out.push(`      <SolidColorBrush x:Key="Ui${id}Brush" Color="${avaloniaColor(hex)}" />`);
    }
    out.push("    </ResourceDictionary>");
  };
  out.push("  <ResourceDictionary.ThemeDictionaries>");
  themed("Default", coloursOf(resolved));
  if (resolved.modes.dark) themed("Dark", coloursOf(resolved, "dark"));
  out.push("  </ResourceDictionary.ThemeDictionaries>");
  for (const [group, tokens] of Object.entries(resolved.groups)) {
    for (const [name, t] of Object.entries(tokens)) {
      const id = `Ui${pascal(member(group, name))}`;
      if (group === "fontSize" || group === "space") out.push(`  <x:Double x:Key="${id}">${toPx(t.value)}</x:Double>`);
      else if (group === "radius") out.push(`  <CornerRadius x:Key="${id}">${toPx(t.value)}</CornerRadius>`);
      else if (group === "font") out.push(`  <FontFamily x:Key="${id}">${xmlEscape(t.value.join(", "))}</FontFamily>`);
      else if (group === "fontWeight") out.push(`  <FontWeight x:Key="${id}">${t.value}</FontWeight>`);
      else if (group === "duration") out.push(`  <x:TimeSpan x:Key="${id}">0:0:${(parseInt(t.value, 10) / 1000).toFixed(3)}</x:TimeSpan>`);
    }
  }
  out.push("</ResourceDictionary>", "");
  return out.join("\n");
}
