// The ui-kit page is complete by construction (COMPANY/UI_STANDARDS.md §2, ui-kit D010). Every project component
// file has a sibling `<name>.states.tsx` listing its states; the page renders them all from a generated registry;
// and every form control the project uses is one the kit's section of the page draws. Nothing on the page is
// written by hand, so nothing can fall behind the app unnoticed.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, posix } from "node:path";
import { walk } from "./raw-values.mjs";

/** Control types the kit's section of the ui-kit page draws in every state. Keep in step with kitchen-sink.tsx. */
export const PAGE_CONTROLS = ["text", "email", "number", "date", "time", "search", "select", "textarea", "radio", "checkbox"];

// Next.js route files are data-bound shells around components; the components inside them carry the states.
const ROUTE_FILES = /^(page|layout|template|loading|error|global-error|not-found|default|route|opengraph-image|icon)\.tsx$/;
const STATES = ".states.tsx";
const COMPONENT = /^export\s+(?:default\s+)?(?:async\s+)?function\s+([A-Z]\w*)/m;

/** The component files under `uiPage.components` that need a states file, relative to the project root. */
export function componentFiles(root, config) {
  const files = [];
  for (const dir of config.uiPage.components) {
    for (const file of walk(join(root, dir), root)) {
      const name = basename(file);
      if (extname(file) !== ".tsx" || name.endsWith(STATES) || name.endsWith(".dev.tsx") || ROUTE_FILES.test(name)) continue;
      if (config.kitDir && file.startsWith(`${config.kitDir}/`)) continue;
      if (COMPONENT.test(readFileSync(join(root, file), "utf8"))) files.push(file);
    }
  }
  return files.sort();
}

export const statesFileOf = (file) => file.replace(/\.tsx$/, STATES);

/** Control types used in the project's sources outside the kit, as `type → first file:line`. */
export function usedControls(root, config) {
  const used = new Map();
  for (const source of config.sources) {
    for (const file of walk(join(root, source), root)) {
      if (![".tsx", ".jsx"].includes(extname(file)) || file.endsWith(STATES)) continue;
      if (config.kitDir && file.startsWith(`${config.kitDir}/`)) continue;
      const text = readFileSync(join(root, file), "utf8");
      // A tag's attributes may span lines, so match whole tags, then report the tag's first line.
      for (const m of text.matchAll(/<(input|select|textarea|Choice)\b([^>]*)>/g)) {
        const type = m[1] === "input" || m[1] === "Choice" ? (/\btype=["']([a-z]+)["']/.exec(m[2])?.[1] ?? "text") : m[1];
        if (type === "hidden" || type === "submit") continue;
        if (!used.has(type)) used.set(type, `${file}:${text.slice(0, m.index).split("\n").length}`);
      }
    }
  }
  return used;
}

/** The registry the ui-kit page imports: every states file, in path order. */
export function renderRegistry(root, config) {
  const registry = config.uiPage.registry;
  const lines = [
    "// Generated by ui-kit: `node scripts/ui-kit/ui-check.mjs --write`. Do not edit; add a `.states.tsx` file instead.",
    'import type { UiStates } from "' + posix.relative(posix.dirname(registry), config.kitDir) + '/ui-page";',
  ];
  const entries = [];
  componentFiles(root, config).forEach((file, i) => {
    if (!existsSync(join(root, statesFileOf(file)))) return;
    let spec = posix.relative(posix.dirname(registry), statesFileOf(file).replace(/\.tsx$/, ""));
    if (!spec.startsWith(".")) spec = `./${spec}`;
    lines.push(`import states${i} from "${spec}";`);
    entries.push(`  { file: "${file}", states: states${i} },`);
  });
  lines.push("", "export const UI_PAGE_STATES: { file: string; states: UiStates }[] = [", ...entries, "];", "");
  return lines.join("\n");
}

// Raw interactive elements a project draws itself. The same element with the same classes in several places is a
// component that was never made, or a kit component that was not found (D010: search, then extend or create).
const RAW_INTERACTIVE = /<(button|a|Link|input|select|textarea)\b([^>]*?)\bclassName=["']([^"']+)["']/g;
export const REPEAT_LIMIT = 3;

/** Raw interactive markup repeated by hand: `<tag> "classes"` → file:line list, only entries at or over REPEAT_LIMIT. */
export function repeatedMarkup(root, config) {
  const seen = new Map();
  for (const source of config.sources) {
    for (const file of walk(join(root, source), root)) {
      if (![".tsx", ".jsx"].includes(extname(file)) || file.endsWith(STATES) || file.endsWith(".dev.tsx")) continue;
      if (config.kitDir && file.startsWith(`${config.kitDir}/`)) continue;
      const text = readFileSync(join(root, file), "utf8");
      for (const m of text.matchAll(RAW_INTERACTIVE)) {
        const key = `<${m[1]}> "${m[3].split(/\s+/).filter(Boolean).sort().join(" ")}"`;
        if (!seen.has(key)) seen.set(key, []);
        seen.get(key).push(`${file}:${text.slice(0, m.index).split("\n").length}`);
      }
    }
  }
  return new Map([...seen].filter(([, at]) => at.length >= REPEAT_LIMIT));
}

/**
 * A states file shows the real component, never a copy: it imports its sibling and draws no markup of its own, so
 * a change to the component is the change on the ui-kit page (D010). Its job is data, not drawing.
 */
export function checkStatesFile(path, text) {
  const own = basename(path).replace(STATES, "");
  const problems = [];
  if (!text.includes(`from "./${own}"`) && !text.includes(`from './${own}'`))
    problems.push(`${path}  does not import ./${own}: a states file shows the real component, never a copy of it`);
  text.split(/\r?\n/).forEach((line, i) => {
    // A JSX tag, not a type argument: `Props<typeof X>` follows an identifier, a tag never does.
    const tag = /(?:^|[^\w$.])<([a-z][\w-]*)[\s/>]/.exec(line);
    if (tag && !/^\s*(\/\/|\*)/.test(line))
      problems.push(
        `${path}:${i + 1}  draws <${tag[1]}> itself: pass data to the component instead, so the page shows only what the site shows`
      );
  });
  return problems;
}

const REUSE =
  "first look for a kit or project component that already does this (docs/usage.md, the ui-kit page); extend it if it nearly fits, create a new one only if its role differs";

/** @returns {string[]} problems */
export function checkUiPage(root, config) {
  if (!config.uiPage) return [];
  const problems = [];
  const allowed = config.allow.uiPage ?? {};
  for (const file of componentFiles(root, config)) {
    if (!existsSync(join(root, statesFileOf(file))) && !allowed[file])
      problems.push(
        `${file}  has no ${basename(statesFileOf(file))}. If it repeats an existing component, use that one instead; otherwise list its states so the ui-kit page shows them`
      );
  }
  for (const file of componentFiles(root, config)) {
    const states = statesFileOf(file);
    if (existsSync(join(root, states))) problems.push(...checkStatesFile(states, readFileSync(join(root, states), "utf8")));
  }
  for (const [type, where] of usedControls(root, config)) {
    if (!PAGE_CONTROLS.includes(type)) problems.push(`${where}  uses a "${type}" control the ui-kit page does not draw: ${REUSE}`);
  }
  for (const [key, at] of repeatedMarkup(root, config)) {
    if (!allowed[key]) problems.push(`${at[0]}  ${key} is drawn by hand ${at.length} times (also ${at.slice(1).join(", ")}): ${REUSE}`);
  }
  const current = readText(join(root, config.uiPage.registry));
  if (current !== renderRegistry(root, config))
    problems.push(`${config.uiPage.registry}  is ${current === null ? "missing" : "out of date"}; run ui-check with --write`);
  return problems;
}

const readText = (path) => (existsSync(path) ? readFileSync(path, "utf8").replaceAll("\r\n", "\n") : null);

/** Writes the registry; returns true when it changed. */
export function writeRegistry(root, config) {
  if (!config.uiPage) return false;
  const path = join(root, config.uiPage.registry);
  const next = renderRegistry(root, config);
  if (readText(path) === next) return false;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next);
  return true;
}
